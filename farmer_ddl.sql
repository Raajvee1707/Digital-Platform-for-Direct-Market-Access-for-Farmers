CREATE TABLE FARMER (
    FARMER_ID NUMBER PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(15),
    EMAIL VARCHAR2(100) UNIQUE,
    ADDRESS VARCHAR2(255),
    FARM_LOCATION VARCHAR2(150)
);

CREATE TABLE BUYER (
    BUYER_ID NUMBER PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(15),
    EMAIL VARCHAR2(100) UNIQUE,
    ADDRESS VARCHAR2(255)
);

CREATE TABLE CATEGORY (
    CATEGORY_ID NUMBER PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255)
);

CREATE TABLE PRODUCT (
    PRODUCT_ID NUMBER PRIMARY KEY,
    FARMER_ID NUMBER NOT NULL REFERENCES FARMER(FARMER_ID),
    NAME VARCHAR2(100) NOT NULL,
    CATEGORY_ID NUMBER REFERENCES CATEGORY(CATEGORY_ID),
    PRICE NUMBER(10,2) NOT NULL CHECK (PRICE >= 0),
    AVAILABLE_QUANTITY NUMBER DEFAULT 0 NOT NULL CHECK (AVAILABLE_QUANTITY >= 0)
);

CREATE TABLE ORDERS (
    ORDER_ID NUMBER PRIMARY KEY,
    BUYER_ID NUMBER NOT NULL REFERENCES BUYER(BUYER_ID),
    ORDER_DATE DATE DEFAULT SYSDATE NOT NULL,
    TOTAL_AMOUNT NUMBER(12,2) DEFAULT 0 CHECK (TOTAL_AMOUNT >= 0),
    ORDER_STATUS VARCHAR2(30) DEFAULT 'Pending'
);

CREATE TABLE ORDER_ITEM (
    ORDER_ID NUMBER REFERENCES ORDERS(ORDER_ID),
    PRODUCT_ID NUMBER REFERENCES PRODUCT(PRODUCT_ID),
    QUANTITY NUMBER NOT NULL CHECK (QUANTITY > 0),
    UNIT_PRICE NUMBER(10,2) NOT NULL CHECK (UNIT_PRICE >= 0),
    PRIMARY KEY (ORDER_ID, PRODUCT_ID)
);

CREATE TABLE NEGOTIATION (
    NEGOTIATION_ID NUMBER PRIMARY KEY,
    BUYER_ID NUMBER NOT NULL REFERENCES BUYER(BUYER_ID),
    FARMER_ID NUMBER NOT NULL REFERENCES FARMER(FARMER_ID),
    PRODUCT_ID NUMBER NOT NULL REFERENCES PRODUCT(PRODUCT_ID),
    STATUS VARCHAR2(30) DEFAULT 'Pending',
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE NEGOTIATION_OFFER (
    OFFER_ID NUMBER PRIMARY KEY,
    NEGOTIATION_ID NUMBER NOT NULL REFERENCES NEGOTIATION(NEGOTIATION_ID),
    PRICE_ORDERED NUMBER(10,2),
    PRICE_OFFERED NUMBER(10,2) NOT NULL CHECK (PRICE_OFFERED >= 0),
    OFFER_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DELIVERY (
    DELIVERY_ID NUMBER PRIMARY KEY,
    ORDER_ID NUMBER NOT NULL UNIQUE REFERENCES ORDERS(ORDER_ID),
    DELIVERY_ADDRESS VARCHAR2(255) NOT NULL,
    DELIVERY_DATE DATE,
    DELIVERY_STATUS VARCHAR2(30) DEFAULT 'Pending',
    TRACKING_INFO VARCHAR2(255)
);

CREATE TABLE REVIEW (
    ORDER_ID NUMBER REFERENCES ORDERS(ORDER_ID),
    PRODUCT_ID NUMBER REFERENCES PRODUCT(PRODUCT_ID),
    RATING NUMBER NOT NULL CHECK (RATING BETWEEN 1 AND 5),
    REVIEW_TEXT VARCHAR2(500),
    REVIEW_DATE DATE DEFAULT SYSDATE,
    PRIMARY KEY (ORDER_ID, PRODUCT_ID)
);